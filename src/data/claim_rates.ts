import rates from './claim_rates.json';
import { LogitpingError } from '../core/errors.js';
import { isIntegerInRange, isRecord, MODEL_ID_PATTERN } from '../util/validate.js';

/** Runs of other models: enrolled ones with the full bank or with their own reference removed, and unenrolled ones. */
export type ClaimPopulation = 'enrolled' | 'removed' | 'unenrolled';
export const CLAIM_POPULATIONS: readonly ClaimPopulation[] = ['enrolled', 'removed', 'unenrolled'];

/** How many runs of one other model, in one population, the claim was accepted for. */
export interface ClaimRow { model: string; population: ClaimPopulation; accepted: number; runs: number }

/** Raw acceptance counts of one claimed model; rates are derived at read time. */
export interface ClaimCounts {
  /** The claimed model's independent runs, or, when it has none, its tuning runs; never both. */
  own: { source: 'independent' | 'tuning'; accepted: number; runs: number };
  /** Sorted by population (enrolled, removed, unenrolled), then by model id. */
  runs: ClaimRow[];
}

/** src/data/claim_rates.json, generated by `npm run bank:evaluate` for the bundled default bank. */
export interface ClaimRatesFile {
  schemaVersion: 1;
  /** `sha256` is that of the bank file's text, as docs/evaluation.json records it. */
  bank: { file: string; sha256: string };
  /** SHA-256 of every corpus whose runs were scored, sorted. */
  corpora: string[];
  rule: 'claimed model in candidates';
  /** Keyed by bank id, in bank order. */
  claims: Record<string, ClaimCounts>;
}

/** Code-unit order, independent of the locale. */
export const compareIds = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);

const SHA256 = /^[0-9a-f]{64}$/;

function check(condition: unknown, field: string): asserts condition {
  if (!condition) throw new LogitpingError('INVALID_BANK', `Invalid claim rates: ${field}`);
}

const counted = (value: Record<string, unknown>) => isIntegerInRange(value.runs, 1, Number.MAX_SAFE_INTEGER)
  && isIntegerInRange(value.accepted, 0, value.runs as number);

/** Validate a claim rate file. Returns an independent copy. */
export function validateClaimRates(input: unknown): ClaimRatesFile {
  check(isRecord(input) && input.schemaVersion === 1, 'unsupported schema');
  check(isRecord(input.bank) && typeof input.bank.file === 'string' && input.bank.file.length > 0
    && typeof input.bank.sha256 === 'string' && SHA256.test(input.bank.sha256), 'bank');
  const corpora = input.corpora;
  check(Array.isArray(corpora) && corpora.every((digest, index) => typeof digest === 'string' && SHA256.test(digest)
    && (index === 0 || compareIds(corpora[index - 1] as string, digest) < 0)), 'corpora must be sorted unique SHA-256 digests');
  check(input.rule === 'claimed model in candidates', 'rule');
  check(isRecord(input.claims), 'claims');
  for (const [id, value] of Object.entries(input.claims)) {
    check(MODEL_ID_PATTERN.test(id), 'claim ids');
    check(isRecord(value) && isRecord(value.own) && (value.own.source === 'independent' || value.own.source === 'tuning') && counted(value.own), `${id} own runs`);
    check(Array.isArray(value.runs), `${id} runs`);
    let previous: { population: number; model: string } | undefined;
    for (const row of value.runs as unknown[]) {
      check(isRecord(row) && typeof row.model === 'string' && MODEL_ID_PATTERN.test(row.model) && row.model !== id
        && CLAIM_POPULATIONS.includes(row.population as ClaimPopulation) && counted(row), `${id} rows`);
      const key = { population: CLAIM_POPULATIONS.indexOf(row.population as ClaimPopulation), model: row.model as string };
      check(!previous || previous.population < key.population || (previous.population === key.population && compareIds(previous.model, key.model) < 0),
        `${id} rows must be sorted by population, then model, without duplicates`);
      previous = key;
    }
  }
  return structuredClone(input) as unknown as ClaimRatesFile;
}

let bundled: ClaimRatesFile | undefined;

/** The bundled claim rate file of the default bank, validated on first use. */
export function bundledClaimRates(): ClaimRatesFile {
  bundled ??= validateClaimRates(rates);
  return bundled;
}
